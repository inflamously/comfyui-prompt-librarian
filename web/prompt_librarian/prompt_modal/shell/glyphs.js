/* Use code points so glyphs survive an incorrect response charset.
 */

export const ARROW = String.fromCharCode(0x2192); // →
export const MIDDOT = String.fromCharCode(0x00b7); // ·
export const CARET = String.fromCharCode(0x25be); // ▾
export const TIMES = String.fromCharCode(0x00d7); // ×
export const LINKED = String.fromCharCode(0x21c5); // ⇅
export const BROKEN = String.fromCharCode(0x2260); // ≠
